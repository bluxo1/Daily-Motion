"""Generate closed response DTOs and validators from checked OpenAPI, not parallel schemas."""

import hashlib
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
contract = root / "contracts/openapi.json"
document = json.loads(contract.read_text(encoding="utf-8"))
schemas = document["components"]["schemas"]
allowed = {
    "$ref",
    "type",
    "title",
    "description",
    "properties",
    "required",
    "additionalProperties",
    "items",
    "minimum",
    "maximum",
    "minLength",
    "maxLength",
    "minItems",
    "maxItems",
    "enum",
    "const",
    "anyOf",
    "oneOf",
    "discriminator",
    "format",
    "pattern",
    "default",
    "x-command-schemas",
}


def check(schema: dict) -> None:
    unexpected = set(schema) - allowed
    if unexpected:
        raise ValueError(f"Unsupported JSON Schema keywords: {unexpected}")
    if schema.get("format") not in (None, "uuid", "date-time"):
        raise ValueError(f"Unsupported JSON Schema format: {schema['format']}")
    for key in ["items", "additionalProperties"]:
        if isinstance(schema.get(key), dict):
            check(schema[key])
    for value in schema.get("properties", {}).values():
        check(value)
    for keyword in ["anyOf", "oneOf"]:
        for value in schema.get(keyword, []):
            check(value)


for schema in schemas.values():
    check(schema)
lines = [
    "// GENERATED by tools/generate_transport.py. Do not edit.",
    "import 'dart:convert';",
    "import '../domain/workout.dart';",
    "import 'contract_validation.dart';",
    f"const transportContractHash = '{hashlib.sha256(contract.read_bytes()).hexdigest()}';",
    "final Json transportSchemas = jsonDecode(r'''"
    + json.dumps(schemas, separators=(",", ":"))
    + "''') as Json;",
    "void validateTransport(String name, Json value) => "
    "validateSchema(value, transportSchemas[name] as Json, transportSchemas);",
]
for name, schema in sorted(schemas.items()):
    if schema.get("type") != "object":
        continue
    lines.extend(
        [
            f"class {name}Dto {{",
            "  final Json json;",
            f"  {name}Dto.fromJson(Json value) : json = copyJson(value) "
            f"{{ validateTransport('{name}', json); }}",
        ]
    )
    for key, prop in schema.get("properties", {}).items():
        dart_name = re.sub(r"_([a-z])", lambda match: match[1].upper(), key)
        dart_type = {
            "string": "String",
            "integer": "int",
            "boolean": "bool",
            "array": "List<dynamic>",
            "object": "Json",
        }.get(prop.get("type"), "Object?")
        if key not in schema.get("required", []):
            dart_type = "Object?"
        lines.append(f"  {dart_type} get {dart_name} => json['{key}'] as {dart_type};")
    lines.append("}")
target = root / "apps/mobile/lib/sync/transport_contract.dart"
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
limits = ["// GENERATED by tools/generate_transport.py. Do not edit."]
for field in ("command_limit", "batch_limit", "page_limit", "snapshot_limit"):
    name = "transport" + "".join(part.capitalize() for part in field.split("_"))
    limits.append(f"const {name} = {schemas['MeResponse']['properties'][field]['const']};")
operation_limit = schemas["PushRequest"]["properties"]["operations"]["maxItems"]
limits.append(f"const transportOperationCountLimit = {operation_limit};")
reason_pattern = schemas["RecordSet"]["properties"]["correction_reason"]["anyOf"][0]["pattern"]
limits.append(f"const transportNonblankReasonPattern = r'''{reason_pattern}''';")
(target.parent / "transport_limits.dart").write_text(
    "\n".join(limits) + "\n", encoding="utf-8", newline="\n"
)
print("Generated mobile transport DTOs")
